class CreateProjectArgs(BaseModel):
    model_config = ConfigDict(extra="forbid")
    kind: Literal["calculator", "python_script", "fastapi_starter", "react_fastapi"] = "calculator"
    name: str = Field(min_length=1, max_length=120)
    directory: str | None = Field(default=None, max_length=512)
    open_in_vscode: bool = True


class RunTestsArgs(BaseModel):
    model_config = ConfigDict(extra="forbid")
    project_dir: str = Field(max_length=1024)


class SyntaxArgs(BaseModel):
    model_config = ConfigDict(extra="forbid")
    path: str = Field(max_length=1024)


class EmptyArgs(BaseModel):
    model_config = ConfigDict(extra="forbid")


def _vscode_executable() -> Path | None:
    which = shutil.which("code")
    if which:
        candidate = Path(which)
        if candidate.suffix.lower() in {".cmd", ".bat"}:
            exe = candidate.parent.parent / "Code.exe"
            if exe.exists():
                return exe
        if candidate.exists():
            return candidate
    return resolve_spec(
        {
            "name": "VS Code",
            "executable": "Code.exe",
            "paths": [r"%LOCALAPPDATA%\Programs\Microsoft VS Code\Code.exe",
                      r"%PROGRAMFILES%\Microsoft VS Code\Code.exe"],
        }
    )


def _syntax_check(files: dict[str, str]) -> list[str]:
    problems = []
    for name, source in files.items():
        if not name.endswith(".py"):
            continue
        try:
            compile(source, name, "exec")
        except SyntaxError as exc:
            problems.append(f"{name}: {exc}")
    return problems


def _open_vscode(project_dir: Path) -> dict[str, Any]:
    executable = _vscode_executable()
    if executable is None:
        return {"opened": False, "reason": "VS Code was not found. Install it or set a shortcut in Settings."}
    process = subprocess.Popen(
        [str(executable), str(project_dir)],
        stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    time.sleep(0.8)
    alive = process.poll() is None
    handoff = executable.suffix.lower() in {".cmd", ".bat"}
    return {"opened": alive or handoff, "pid": process.pid,
            "executable": str(executable), "exit_code": None if alive else process.returncode}


async def create_project_handler(args: CreateProjectArgs, ctx: ToolContext) -> ToolResult:
    base = Path(os.path.expandvars(args.directory)).expanduser() if args.directory else ctx.settings.project_root
    ctx.policy.ensure_writable(base)
    base.mkdir(parents=True, exist_ok=True)
    project_dir = base / slugify(args.name)
    ctx.policy.ensure_writable(project_dir)
    if project_dir.exists():
        raise ToolError(
            f"{project_dir} already exists, so I did not touch it.",
            hint="Pick another project name or remove/move the existing folder yourself.",
        )
    files = TEMPLATES[args.kind]
    project_dir.mkdir(parents=True)
    written = []
    for relative, source in files.items():
        target = project_dir / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        text = textwrap.dedent(source).lstrip("\n")
        target.write_text(text, encoding="utf-8")
        written.append(str(target.relative_to(project_dir)))

    problems = _syntax_check({name: textwrap.dedent(src).lstrip("\n") for name, src in files.items()})
    if problems:
        raise ToolError("Generated code failed its syntax check: " + "; ".join(problems))

    ctx.audit.record(ctx.actor, "code.create_project", Risk.MODERATE.value,
                     {"kind": args.kind, "path": str(project_dir)}, "ok")
    vscode = {"opened": False, "reason": "Not requested."}
    if args.open_in_vscode:
        vscode = await asyncio.to_thread(_open_vscode, project_dir)

    summary = (
        f"Created a {args.kind.replace('_', ' ')} project at {project_dir} "
        f"with {len(written)} files. Syntax check passed."
    )
    if args.open_in_vscode:
        summary += " Opened it in VS Code." if vscode.get("opened") else (
            " VS Code could not be opened: " + str(vscode.get("reason"))
        )
    return ToolResult.success(summary, path=str(project_dir), files=written,
                              vscode=vscode, kind=args.kind)


async def run_tests_handler(args: RunTestsArgs, ctx: ToolContext) -> ToolResult:
    project_dir = Path(os.path.expandvars(args.project_dir)).expanduser()
    ctx.policy.ensure_writable(project_dir)
    if not project_dir.is_dir():
        return ToolResult.failure(f"Project folder not found: {project_dir}")
    has_tests = any(project_dir.rglob("test_*.py")) or any(project_dir.rglob("*_test.py"))
    if not has_tests:
        return ToolResult.failure(f"No test files were found in {project_dir}.")
    command = [sys.executable, "-m", "unittest", "discover", "-v"]
    process = await asyncio.to_thread(
        subprocess.run, command, cwd=str(project_dir), capture_output=True,
        text=True, timeout=90, check=False,
    )
    output = (process.stdout or "") + (process.stderr or "")
    passed = process.returncode == 0
    ctx.repo.add_task_event(ctx.task_id, "info" if passed else "error",
                            f"Test run exited with {process.returncode}")
    ctx.audit.record(ctx.actor, "code.run_tests", Risk.MODERATE.value,
                     {"path": str(project_dir), "exit": process.returncode},
                     "ok" if passed else "failed")
    summary = (
        f"Tests {'passed' if passed else 'failed'} in {project_dir.name} "
        f"(exit code {process.returncode})."
    )
    return ToolResult(ok=passed, summary=summary, error=None if passed else summary,
                      data={"output": output[-4000:], "exit_code": process.returncode})


async def check_syntax_handler(args: SyntaxArgs, ctx: ToolContext) -> ToolResult:
    path = Path(os.path.expandvars(args.path)).expanduser()
    ctx.policy.ensure_readable(path)
    if not path.is_file():
        return ToolResult.failure(f"File not found: {path}")
    source = path.read_text(encoding="utf-8", errors="replace")
    try:
        compile(source, str(path), "exec")
    except SyntaxError as exc:
        return ToolResult.failure(
            f"Syntax error in {path.name} on line {exc.lineno}: {exc.msg}",
            line=exc.lineno, offset=exc.offset,
        )
    return ToolResult.success(f"{path.name} is syntactically valid Python.")


async def list_templates_handler(_: EmptyArgs, ctx: ToolContext) -> ToolResult:
    return ToolResult.success(
        "Available templates: " + ", ".join(sorted(TEMPLATES)) + ".",
        templates=sorted(TEMPLATES), project_root=str(ctx.settings.project_root),
    )


def build() -> list[ToolDefinition]:
    return [
        ToolDefinition(
            name="code.create_project",
            description="Generate a Python calculator, starter script, or FastAPI project and open it in VS Code.",
            args_model=CreateProjectArgs,
            risk=Risk.MODERATE,
            handler=create_project_handler,
            category="coding",
        ),
        ToolDefinition(
            name="code.run_tests",
            description="Run unittest discovery inside an approved project folder.",
            args_model=RunTestsArgs,
            risk=Risk.MODERATE,
            handler=run_tests_handler,
            confirm=True,
            category="coding",
        ),
        ToolDefinition(
            name="code.check_syntax",
            description="Check a Python file for syntax errors without executing it.",
            args_model=SyntaxArgs,
            risk=Risk.LOW,
            handler=check_syntax_handler,
            category="coding",
        ),
        ToolDefinition(
            name="code.list_templates",
            description="List available project templates and the configured project root.",
            args_model=EmptyArgs,
            risk=Risk.LOW,
            handler=list_templates_handler,
            category="coding",
        ),
    ]
